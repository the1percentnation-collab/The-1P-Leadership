#!/usr/bin/env node
// Builds the public pages of the essay series from its markdown:
//   public/reads.html          the archive, served at /reads
//   public/reads/<slug>.html   one page per essay, served at /reads/<slug>
//
// Each essay page is real HTML with its own title, description and share
// preview, and carries the essay's opening paragraphs. The full text is not
// in these files: it lives in Firestore (written by seed-focus-tax.js) and
// public/js/reads-page.js swaps it in for a member. So a shared link shows a
// proper preview and the opening is readable by anyone, while the rest of
// the essay stays behind a free portal account.
//
// No credentials needed. Run after editing an essay, and commit the output:
//   cd scripts && node build-reads.js
// `node build-reads.js --check` exits non-zero if the committed pages are
// out of date (tests/reads.test.cjs runs it).

const fs = require('fs');
const path = require('path');
const { escapeHtml, smartQuotes } = require('./lib/markdown');

// Every piece of copy on these pages gets the same curly quotes as the essays.
const esc = (s) => escapeHtml(smartQuotes(s));
const { loadSeries } = require('./lib/essays');

const PUBLIC = path.join(__dirname, '..', 'public');
const SITE = 'https://the1pnation.com';
const AVATAR = '/assets/founder-headshot-square.jpg';
const OG_IMAGE = `${SITE}/assets/founder-stage-banner.jpg`;

function head({ title, description, url, type = 'article' }) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <!-- Generated by scripts/build-reads.js from scripts/focus-tax-content. Do not edit by hand. -->
  <script async src="https://www.googletagmanager.com/gtag/js?id=G-RBH536HRZE"></script>
  <script>window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments);}gtag("js",new Date());gtag("config","G-RBH536HRZE");</script>
  <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
  <meta name="theme-color" content="#FBFAF7" media="(prefers-color-scheme: light)">
  <meta name="theme-color" content="#0E0E0E" media="(prefers-color-scheme: dark)">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}">
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="${type}">
  <meta property="og:site_name" content="The One Percent">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(description)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${OG_IMAGE}">
  <meta name="twitter:card" content="summary_large_image">
  <link rel="icon" href="/assets/favicon.jpg">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Newsreader:ital,opsz,wght@0,6..72,400;0,6..72,600;1,6..72,400&family=Outfit:wght@400;500;600&family=Space+Mono&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="/assets/reads.css">
</head>`;
}

function nav(series, { progress = false } = {}) {
  return `<nav class="r-nav">
    <div class="in">
      <a class="r-brand" href="/reads"><img src="/assets/academy-logo.png" alt=""><span>${esc(series.title)}</span></a>
      <div class="r-links" id="r-account">
        <a class="r-link hide-sm" href="/reads">Archive</a>
        <a class="r-link" href="/login?next=${encodeURIComponent('/reads')}" data-auth="out">Log in</a>
        <a class="r-btn r-btn-ghost" href="/dashboard" data-auth="in" hidden>Portal</a>
      </div>
    </div>
    ${progress ? '<div class="r-progress" id="r-progress"></div>' : ''}
  </nav>`;
}

function byline(series, meta, extra = '') {
  return `<div class="r-byline">
      <img src="${AVATAR}" alt="">
      <div><div class="who">${esc(series.author)}</div><div class="meta">${meta}</div></div>${extra}
    </div>`;
}

function essayPage(series, essays, e) {
  const url = `${SITE}/reads/${e.slug}`;
  const next = essays.find((x) => x.issue > e.issue) || null;
  const meta = [e.date ? esc(e.date) : '', `${esc(e.readTime)} read`].filter(Boolean).join(' · ');
  const config = { series: series.slug, slug: e.slug, title: e.title };
  return `${head({ title: `${e.title} | ${series.title}`, description: e.hook, url })}
<body>
  ${nav(series, { progress: true })}
  <main class="r-wrap">
    <article>
      <a class="r-kicker" href="/reads">${esc(series.title)} · No. ${e.issueLabel}</a>
      <h1 class="r-title">${esc(e.title)}</h1>
      <p class="r-dek">${esc(e.hook)}</p>
      ${byline(series, meta, '\n      <button class="r-btn r-btn-ghost share" type="button" id="r-share">Share</button>')}
      <div class="prose r-fade" id="r-body">
${e.previewHtml}
      </div>
      <section class="r-gate" id="r-gate" aria-labelledby="r-gate-h">
        <h2 id="r-gate-h">Keep reading</h2>
        <p class="lead">${esc(series.title)} is free for One Percent members. Create your free portal account to finish this essay and read the whole series.</p>
        <form class="r-form" id="r-form" novalidate>
          <label for="r-name">First name</label>
          <input id="r-name" name="name" autocomplete="given-name" autocapitalize="words" enterkeyhint="next" required>
          <label for="r-email">Email</label>
          <input id="r-email" name="email" type="email" autocomplete="email" inputmode="email" autocapitalize="off" autocorrect="off" spellcheck="false" enterkeyhint="go" required>
          <button class="r-btn r-btn-red" type="submit" id="r-go">Keep reading, free</button>
          <p class="r-err" id="r-err" role="alert"></p>
        </form>
        <p class="r-fine">No password needed now. We create your free One Percent portal account and email you a link to set your password. Already a member? <a href="/login?next=${encodeURIComponent(`/reads/${e.slug}`)}">Log in</a>. By continuing you agree to our <a href="/terms">terms</a> and <a href="/privacy">privacy policy</a>.</p>
      </section>
    </article>
    <section class="r-end" id="r-end" hidden>
      ${next ? `<div class="lbl">Next in the series</div>
      <a class="r-next" href="/reads/${next.slug}">
        <div class="lbl">No. ${next.issueLabel} · ${esc(next.readTime)} read</div>
        <div class="t">${esc(next.title)}</div>
        <div class="d">${esc(next.hook)}</div>
      </a>` : `<div class="lbl">You have read the series</div>`}
      <div class="r-end-actions">
        <a class="r-btn r-btn-ghost" href="/reads">All essays</a>
        <a class="r-btn r-btn-ghost" href="/assessments">Take a free assessment</a>
      </div>
    </section>
  </main>
  <script type="application/json" id="r-config">${JSON.stringify(config).replace(/</g, '\\u003c')}</script>
  <script type="module" src="/js/reads-page.js"></script>
</body>
</html>
`;
}

function archivePage(series, essays) {
  const url = `${SITE}/reads`;
  const total = essays.reduce((n, e) => n + (parseInt(e.readTime, 10) || 0), 0);
  const items = essays.map((e) => `
    <li><a href="/reads/${e.slug}">
      <span class="no">${e.issueLabel}</span>
      <span class="t">${esc(e.title)}</span>
      <span class="d">${esc(e.hook)}</span>
      <span class="m">${esc(e.readTime)} read</span>
    </a></li>`).join('');
  return `${head({ title: `${series.title} | The One Percent`, description: series.tagline, url, type: 'website' })}
<body>
  ${nav(series)}
  <header class="r-hero">
    <div class="r-kicker">A series from The One Percent</div>
    <h1>${esc(series.title)}</h1>
    <p class="tag">${esc(series.tagline)}</p>
    <p class="desc">${esc(series.description)}</p>
    ${byline(series, `${essays.length} essays · about ${total} minutes in all · free for members`)}
  </header>
  <ol class="r-list">${items}
  </ol>
  <script type="module" src="/js/reads-page.js"></script>
</body>
</html>
`;
}

function build() {
  const { series, essays } = loadSeries();
  const files = new Map();
  files.set(path.join(PUBLIC, 'reads.html'), archivePage(series, essays));
  for (const e of essays) files.set(path.join(PUBLIC, 'reads', `${e.slug}.html`), essayPage(series, essays, e));
  return { essays, files };
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const { essays, files } = build();
  const dir = path.join(PUBLIC, 'reads');
  const existing = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.html')).map((f) => path.join(dir, f)) : [];
  const stale = existing.filter((f) => !files.has(f));

  if (check) {
    const drift = [...files].filter(([f, html]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== html).map(([f]) => f);
    const problems = [...drift, ...stale].map((f) => path.relative(PUBLIC, f));
    if (problems.length) {
      console.error(`Reads pages are out of date: ${problems.join(', ')}\nRun: cd scripts && node build-reads.js`);
      process.exit(1);
    }
    console.log(`Reads pages are current (${essays.length} essays).`);
  } else {
    fs.mkdirSync(dir, { recursive: true });
    for (const f of stale) fs.unlinkSync(f);
    for (const [f, html] of files) fs.writeFileSync(f, html);
    console.log(`Built /reads and ${essays.length} essay pages.`);
  }
}

module.exports = { build };
