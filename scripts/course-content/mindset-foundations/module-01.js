<p>Most courses start with the teaching. This one starts with a measurement, because a mindset shift you cannot measure is a mindset shift you will argue with yourself about six months from now. You will remember feeling different. You will not remember what was actually true before. So before the first lesson, you are going to write down where you stand.</p>
